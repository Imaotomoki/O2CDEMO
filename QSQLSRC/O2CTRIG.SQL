-- =====================================================================
-- O2CTRIG - 変更履歴(CHANGELOGP)を残すトリガー
-- 修正#LOG: 新規作成。受注・請求書・入金の追加と、状態・金額の変更を
--   CHANGELOGP に記録する(OLDVAL/NEWVAL は JSON 形式)
--   作成: RUNSQLSTM SRCFILE(ライブラリー/QSQLSRC) SRCMBR(O2CTRIG)
--         COMMIT(*NONE) NAMING(*SQL) DFTRDBCOL(ライブラリー)
--   採番: O2C_LOGID_SEQ(在庫トリガー INVTRIGGER と共通)
-- =====================================================================
CREATE OR REPLACE TRIGGER O2C_SOH_INS AFTER INSERT ON SORDERHP
  REFERENCING NEW AS N FOR EACH ROW MODE DB2ROW
  INSERT INTO CHANGELOGP (LOGID, TBLNAME, RECID, ACTION, CHGBY, CHGAT,
         OLDVAL, NEWVAL)
  VALUES (NEXT VALUE FOR O2C_LOGID_SEQ, 'SORDERHP', N.SONUM, 'INSERT',
         USER, CURRENT TIMESTAMP, ' ',
         '{"STATUS":"' CONCAT RTRIM(N.STATUS) CONCAT '","TOTAMT":'
         CONCAT TRIM(CHAR(N.TOTAMT)) CONCAT '}');

CREATE OR REPLACE TRIGGER O2C_SOH_UPD AFTER UPDATE ON SORDERHP
  REFERENCING OLD AS O NEW AS N FOR EACH ROW MODE DB2ROW
  WHEN (O.STATUS <> N.STATUS OR O.TOTAMT <> N.TOTAMT)
  INSERT INTO CHANGELOGP (LOGID, TBLNAME, RECID, ACTION, CHGBY, CHGAT,
         OLDVAL, NEWVAL)
  VALUES (NEXT VALUE FOR O2C_LOGID_SEQ, 'SORDERHP', N.SONUM, 'UPDATE',
         USER, CURRENT TIMESTAMP,
         '{"STATUS":"' CONCAT RTRIM(O.STATUS) CONCAT '","TOTAMT":'
         CONCAT TRIM(CHAR(O.TOTAMT)) CONCAT '}',
         '{"STATUS":"' CONCAT RTRIM(N.STATUS) CONCAT '","TOTAMT":'
         CONCAT TRIM(CHAR(N.TOTAMT)) CONCAT '}');

